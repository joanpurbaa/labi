import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "node_modules/@phosphor-icons/core/assets/duotone");
const OUT_DIR = join(root, "components/icons");
const OUT_FILE = join(OUT_DIR, "duoIconData.ts");

// nama-duotone (memuat kedua path; pertama=tint opacity, kedua=garis)
const ICONS = [
	"chat-circle",
	"bell",
	"microphone",
	"clock-counter-clockwise",
	"chart-bar",
	"book-open",
	"chart-line-up",
	"caret-right",
	"house",
	"user",
	"eye",
	"eye-slash",
	"sign-out",
	"check",
	"trash",
	"heart",
	"lock",
	"clock",
	"calendar",
	"sparkle",
	"smiley",
	"moon",
	"star",
	"waveform",
	"info",
	"file-text",
	"arrow-right",
];

function parse(name) {
	const file = join(SRC, `${name}-duotone.svg`);
	const svg = readFileSync(file, "utf8");
	const paths = [...svg.matchAll(/<path d="([^"]+)"(?:\s+opacity="([^"]+)")?\/?>/g)];
	if (paths.length !== 2) {
		throw new Error(
			`${name}: harapkan 2 <path> per SVG duotone, dapat ${paths.length}`,
		);
	}
	// baris pertama ber-opacity = isian lembut (tint); kedua = garis.
	const [a, b] = paths;
	if (!a[2]) {
		throw new Error(`${name}: path pertama tidak punya opacity (bukan duotone?)`);
	}
	return { tintD: a[1], lineD: b[1] };
}

const out = [];
out.push("// GENERATED by scripts/build-duo-icons.mjs — jangan diedit manual.");
out.push("// Sumber: @phosphor-icons/core (MIT). viewBox selalu \"0 0 256 256\".");
out.push("");
out.push("export type DuoIconName =");
out.push(
	ICONS.map((n) => `\t| "${n}"`).join("\n") + ";",
);
out.push("");
out.push("export const duoIcons: Record<DuoIconName, { tintD: string; lineD: string }> = {");
for (const name of ICONS) {
	const { tintD, lineD } = parse(name);
	out.push(`\t${JSON.stringify(name)}: {`);
	out.push(`\t\ttintD: ${JSON.stringify(tintD)},`);
	out.push(`\t\tlineD: ${JSON.stringify(lineD)},`);
	out.push("\t},");
}
out.push("};");
out.push("");

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, out.join("\n"));
let total = 0;
for (const name of ICONS) {
	total += readFileSync(join(SRC, `${name}-duotone.svg`)).length;
}
console.log(`OK: ${ICONS.length} ikon -> ${OUT_FILE} (sumber ${total} bytes)`);